package com.lomipe.devhub.ui

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.os.PersistableBundle
import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.text.KeyboardOptions
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.input.KeyboardType
import androidx.compose.ui.text.input.PasswordVisualTransformation
import androidx.compose.ui.unit.dp
import com.lomipe.devhub.core.ReleaseKey
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import java.util.Base64

@Composable
fun ReleaseSigningPanel() {
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()
    var alias by remember { mutableStateOf("maxrepo") }
    var password by remember { mutableStateOf("") }
    var confirm by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<ReleaseKey.Generated?>(null) }
    var message by remember { mutableStateOf("") }
    var busy by remember { mutableStateOf(false) }
    var backedUp by remember { mutableStateOf(false) }
    var ask by remember { mutableStateOf(false) }
    var copyAsk by remember { mutableStateOf(false) }
    DisposableEffect(Unit) { onDispose { generated?.bytes?.fill(0) } }
    val export = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/x-pkcs12")) { uri ->
        val item = generated
        if (uri != null && item != null) {
            busy = true
            scope.launch {
                try {
                    withContext(Dispatchers.IO) {
                        ctx.contentResolver.openOutputStream(uri, "wt")?.use { it.write(item.bytes) } ?: error("Cannot open destination")
                    }
                    backedUp = true
                    message = "Encrypted keystore exported. Keep a separate secure backup."
                } catch (e: CancellationException) { throw e }
                catch (_: Exception) { message = "Export failed. Choose another location." }
                finally { busy = false }
            }
        }
    }
    MaxHeading("Release signing", "Generate a permanent signing key on your phone.")
    MaxPanel {
        Text("Already have a release key?", style = MaterialTheme.typography.titleMedium)
        Note("Reuse the existing key if your APK was already permanently signed. A different certificate cannot normally update it.")
    }
    Spacer(Modifier.height(12.dp))
    if (generated == null) {
        MaxPanel {
            Field("Key alias", alias, { if (!busy) alias = it })
            OutlinedTextField(value = password, onValueChange = { password = it }, enabled = !busy,
                label = { Text("Keystore password (12+ characters)") },
                visualTransformation = PasswordVisualTransformation(),
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                singleLine = true, modifier = Modifier.fillMaxWidth())
            OutlinedTextField(value = confirm, onValueChange = { confirm = it }, enabled = !busy,
                label = { Text("Confirm password") },
                visualTransformation = PasswordVisualTransformation(),
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                singleLine = true, modifier = Modifier.fillMaxWidth())
            Note("RSA 3072-bit · PKCS#12 · 100-year certificate. Use the same password for key and store.")
            Button(onClick = { ask = true }, enabled = !busy && alias.matches(Regex("[a-zA-Z0-9_-]{1,40}")) && password.length >= 12 && password == confirm,
                modifier = Modifier.fillMaxWidth()) { Text("Generate permanent key") }
        }
    } else {
        MaxPanel {
            Text("Key generated", style = MaterialTheme.typography.titleMedium)
            Note("Alias: " + alias)
            Note("Certificate SHA-256:")
            generated?.let { Text(it.fingerprint, style = MaterialTheme.typography.bodySmall) }
            OutlinedButton(onClick = { generated?.let {
                val manager = ctx.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                manager.setPrimaryClip(ClipData.newPlainText("Certificate SHA-256", it.fingerprint))
            } }) { Text("Copy certificate fingerprint") }
            Button(onClick = { export.launch("maxrepo-release.p12") }, enabled = !busy, modifier = Modifier.fillMaxWidth()) { Text("Export encrypted keystore") }
            Note("Choose a trusted local destination and make a separate encrypted backup. Never commit this file.")
            if (backedUp) {
                OutlinedButton(onClick = { copyAsk = true }, enabled = !busy) { Text("Copy Base64 for GitHub secret") }
                OutlinedButton(onClick = {
                    (ctx.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager).clearPrimaryClip()
                    message = "Clipboard cleared."
                }) { Text("Clear clipboard") }
            }
            TextButton(onClick = { generated?.bytes?.fill(0); generated = null; backedUp = false; message = "Session cleared. Keep your backup." },
                enabled = !busy && backedUp) { Text("Finish / clear session") }
        }
    }
    if (busy) LinearProgressIndicator(Modifier.fillMaxWidth())
    if (message.isNotEmpty()) Note(message)
    Spacer(Modifier.height(12.dp))
    MaxPanel {
        Text("GitHub signing setup", style = MaterialTheme.typography.titleMedium)
        Note("Use environment maxrepo-production. Add LOMIPE_KEYSTORE_BASE64, LOMIPE_KEYSTORE_PASSWORD, LOMIPE_KEY_ALIAS and LOMIPE_KEY_PASSWORD as secrets. Add MAXREPO_CERT_SHA256 as a variable. The key and store passwords are identical.")
        Note("No key or password is uploaded automatically. Keep the same certificate for future releases.")
    }
    if (ask) AlertDialog(onDismissRequest = { ask = false }, title = { Text("Create a signing identity?") },
        text = { Text("Only create a new key if you have no existing release key. Losing the key can prevent future updates. Export it before leaving.") },
        dismissButton = { TextButton(onClick = { ask = false }) { Text("Cancel") } },
        confirmButton = { TextButton(onClick = {
            ask = false; busy = true
            val chars = password.toCharArray()
            val keyAlias = alias
            password = ""; confirm = ""
            scope.launch {
                try {
                    generated = withContext(Dispatchers.Default) {
                        val result = ReleaseKey.generate(keyAlias, chars)
                        check(ReleaseKey.inspect(result.bytes, keyAlias, chars) == result.fingerprint)
                        result
                    }
                    message = "Key created and verified locally. Export it now."
                } catch (e: CancellationException) { throw e }
                catch (_: Exception) { message = "Key generation failed. No key was uploaded." }
                finally { chars.fill('\u0000'); busy = false }
            }
        }) { Text("Create key") } })
    if (copyAsk) AlertDialog(onDismissRequest = { copyAsk = false }, title = { Text("Copy sensitive keystore?") },
        text = { Text("Base64 is not encryption. Clipboard history or sync may retain this encrypted private keystore. Paste only into the GitHub secret field, then clear your clipboard.") },
        dismissButton = { TextButton(onClick = { copyAsk = false }) { Text("Cancel") } },
        confirmButton = { TextButton(onClick = {
            copyAsk = false
            generated?.let {
                val clip = ClipData.newPlainText("Sensitive keystore", Base64.getEncoder().encodeToString(it.bytes))
                if (android.os.Build.VERSION.SDK_INT >= 24) clip.description.extras =
                    PersistableBundle().apply { putBoolean("android.content.extra.IS_SENSITIVE", true) }
                (ctx.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager).setPrimaryClip(clip)
                message = "Copied. Paste into LOMIPE_KEYSTORE_BASE64 only."
            }
        }) { Text("Copy") } })
}
